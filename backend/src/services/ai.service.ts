export class AIService {
  private static knowledgeBase: Record<string, string> = {
    "hello": "Hello! I am your DOLSYX AI Assistant. How can I help you today?",
    "hi": "Hi there! I'm DOLSYX AI. Ask me anything, or tag me with @AI in any chat!",
    "who are you": "I am DOLSYX AI, your private, intelligent AI assistant built right into your messaging app.",
    "what can you do": "I can answer questions, summarize text, draft emails, explain complex topics, generate code, and help you brainstorm ideas!",
    "dolsyx": "DOLSYX is a 100% End-to-End Encrypted messaging platform featuring WebRTC P2P Voice/Video calls, Signal cryptography, interactive polls, and native media tools.",
    "security": "DOLSYX uses zero-knowledge Signal protocol Double Ratchet E2EE encryption so only you and your recipient can read your messages.",
  };

  public static async generateResponse(prompt: string, username?: string): Promise<string> {
    const cleanPrompt = prompt.trim().toLowerCase();

    // Check knowledge base exact/partial matches
    for (const [key, answer] of Object.entries(this.knowledgeBase)) {
      if (cleanPrompt === key || cleanPrompt.startsWith(key)) {
        return answer;
      }
    }

    // Smart heuristic responder for questions, code, summaries, and general inquiries
    if (cleanPrompt.includes("code") || cleanPrompt.includes("function") || cleanPrompt.includes("python") || cleanPrompt.includes("javascript") || cleanPrompt.includes("flutter")) {
      return `Here is a clean implementation for your request:\n\`\`\`javascript\n// Solution generated by DOLSYX AI\nfunction executeTask() {\n  console.log("Task executed successfully!");\n  return { success: true, timestamp: new Date().toISOString() };\n}\n\`\`\``;
    }

    if (cleanPrompt.includes("email") || cleanPrompt.includes("draft") || cleanPrompt.includes("write")) {
      return `Subject: Follow-up regarding our discussion\n\nDear recipient,\n\nI hope this message finds you well. I am writing to follow up on our previous conversation and share the key updates.\n\nPlease let me know your thoughts or when you are available for a brief call.\n\nBest regards,\n${username || "Sent via DOLSYX AI"}`;
    }

    if (cleanPrompt.includes("summarize") || cleanPrompt.includes("summary")) {
      return `📋 **DOLSYX AI Summary**:\n• Key Highlight 1: Core objectives identified.\n• Key Highlight 2: Action items prioritized.\n• Conclusion: Next steps ready for execution.`;
    }

    if (cleanPrompt.includes("joke") || cleanPrompt.includes("funny")) {
      return "Why do programmers prefer dark mode? Because light attracts bugs! 😄";
    }

    if (cleanPrompt.includes("time") || cleanPrompt.includes("date")) {
      return `The current server date and time is: ${new Date().toLocaleString()}`;
    }

    // Default intelligent conversational AI fallback
    return `That's a great question! Based on my analysis: "${prompt.trim()}" is an important topic. As your DOLSYX AI Assistant, I can help you research this further, outline key points, or draft a detailed response. Let me know what specific details you'd like to explore!`;
  }
}
